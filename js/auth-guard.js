// ทุกหน้ายกเว้น login.html ต้องรอผลจากฟังก์ชันนี้ก่อนค่อยอ่าน/เขียน Firestore
// ─────────────────────────────────────────────────────────────

// เรียกใช้แบบ: เมื่อรู้ผู้ใช้(function (ผู้ใช้) { ...โค้ดของหน้านี้... });
// ถ้ายังไม่ได้ล็อกอิน จะเด้งไปหน้า login.html ให้อัตโนมัติ (พร้อมจำหน้าที่ตั้งใจจะมาไว้)
function เมื่อรู้ผู้ใช้(callback) {
  auth.onAuthStateChanged(function (ผู้ใช้) {
    if (!ผู้ใช้) {
      var หน้าปัจจุบัน = location.pathname.split("/").pop() || "index.html";
      location.href = "login.html?redirect=" + encodeURIComponent(หน้าปัจจุบัน);
      return;
    }
    callback(ผู้ใช้);
  });
}
